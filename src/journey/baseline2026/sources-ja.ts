export const JAPANESE_SOURCE_SECTIONS = SOURCE_SECTIONS.map((source, index) => {
  const localized = sections[index]
  const originals = source.paragraphs ?? source.items ?? []
  if (localized?.original !== source.title.en || localized.entries.length !== originals.length) {
    throw new Error(`Japanese source alignment mismatch: ${source.title.en}`)
  }
  return {
    title: localized.title,
    list: Boolean(source.items),
    entries: localized.entries.map((entry, i) => {
      const urls = originals[i].en.match(/https?:\/\/[^\s)）]+/g) ?? []
      return [entry, ...urls].join(' ')
    }),
  }
})
